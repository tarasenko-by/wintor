// Wintor icon tool.
//
// Hugeicons free icons are stroke drawings (1.5 px lines on a 24x24 grid), but WinUI's PathIcon
// can only fill. This tool keeps the original SVGs in the app's Assets/Icons folder and turns
// every stroke into an exact filled outline, so icons work anywhere an IconElement is accepted
// and follow Foreground/theme.
//
//   dotnet run --project tools/Wintor.IconTool -- import <core-free-icons package dir> <name>...
//       Copies icons (e.g. "download-01", or "2nd-bracket=SecondBracketIcon") from an extracted
//       @hugeicons/core-free-icons npm package into src/Wintor.App/Assets/Icons as SVG,
//       then regenerates the C# file.
//   dotnet run --project tools/Wintor.IconTool -- generate
//       Regenerates src/Wintor.App/Icons/HugeIcons.g.cs from Assets/Icons/*.svg.

using System.Globalization;
using System.Text;
using System.Text.RegularExpressions;
using System.Xml.Linq;
using SkiaSharp;

string root = FindRepoRoot();
string iconsDir = Path.Combine(root, "src", "Wintor.App", "Assets", "Icons");
string outputFile = Path.Combine(root, "src", "Wintor.App", "Icons", "HugeIcons.g.cs");

switch (args.FirstOrDefault())
{
    case "import" when args.Length >= 3:
        Import(args[1], args[2..]);
        Generate();
        break;
    case "generate":
        Generate();
        break;
    case "preview" when args.Length >= 2:
        Preview(args[1]);
        break;
    case "logo":
        Logo();
        break;
    default:
        Console.Error.WriteLine("Usage: import <package-dir> <icon-name>... | generate | preview <out.png> | logo");
        return 1;
}

return 0;

void Import(string packageDir, string[] names)
{
    Directory.CreateDirectory(iconsDir);
    foreach (string spec in names)
    {
        string[] parts = spec.Split('=', 2);
        string name = parts[0];
        string component = parts.Length > 1 ? parts[1] : ToPascal(name) + "Icon";
        string source = Path.Combine(packageDir, "dist", "esm", component + ".js");
        if (!File.Exists(source))
        {
            throw new FileNotFoundException($"'{component}' not found in the package; pass name=ExportName.", source);
        }

        File.WriteAllText(Path.Combine(iconsDir, name + ".svg"), JsToSvg(File.ReadAllText(source)));
        Console.WriteLine($"imported {name}");
    }
}

void Generate()
{
    var icons = Directory.GetFiles(iconsDir, "*.svg")
        .Select(path => (Name: Path.GetFileNameWithoutExtension(path), Data: Outline(XDocument.Load(path))))
        .OrderBy(i => i.Name, StringComparer.Ordinal)
        .ToList();

    var code = new StringBuilder();
    code.AppendLine("// <auto-generated>");
    code.AppendLine("// Generated by tools/Wintor.IconTool from Assets/Icons/*.svg — do not edit; run the tool instead.");
    code.AppendLine("// Icons: Hugeicons free set (Stroke Rounded), MIT License, https://hugeicons.com");
    code.AppendLine("// </auto-generated>");
    code.AppendLine();
    code.AppendLine("namespace Wintor.App.Icons;");
    code.AppendLine();
    code.AppendLine("public enum HugeIconKind");
    code.AppendLine("{");
    foreach (var icon in icons)
    {
        code.AppendLine($"    {ToPascal(icon.Name)},");
    }

    code.AppendLine("}");
    code.AppendLine();
    code.AppendLine("internal static class HugeIconData");
    code.AppendLine("{");
    code.AppendLine("    /// <summary>Filled outline in path markup syntax, on a 24x24 grid.</summary>");
    code.AppendLine("    public static string Get(HugeIconKind kind) => kind switch");
    code.AppendLine("    {");
    foreach (var icon in icons)
    {
        code.AppendLine($"        HugeIconKind.{ToPascal(icon.Name)} => \"{icon.Data}\",");
    }

    code.AppendLine("        _ => throw new ArgumentOutOfRangeException(nameof(kind)),");
    code.AppendLine("    };");
    code.AppendLine("}");

    Directory.CreateDirectory(Path.GetDirectoryName(outputFile)!);
    File.WriteAllText(outputFile, code.ToString().ReplaceLineEndings("\r\n"));
    Console.WriteLine($"generated {icons.Count} icons -> {Path.GetRelativePath(root, outputFile)}");
}

// Renders the filled outlines (what the app will show) in a grid, to eyeball the conversion.
void Preview(string pngPath)
{
    string[] files = Directory.GetFiles(iconsDir, "*.svg").Order(StringComparer.Ordinal).ToArray();
    const int Cell = 96, Columns = 8;
    int rows = (files.Length + Columns - 1) / Columns;
    using var surface = SKSurface.Create(new SKImageInfo(Columns * Cell, rows * Cell));
    SKCanvas canvas = surface.Canvas;
    canvas.Clear(SKColors.White);
    using var paint = new SKPaint { Color = SKColors.Black, IsAntialias = true, Style = SKPaintStyle.Fill };

    for (int i = 0; i < files.Length; i++)
    {
        string outline = Outline(XDocument.Load(files[i]));
        using SKPath path = SKPath.ParseSvgPathData(outline[3..]);
        path.FillType = outline.StartsWith("F0") ? SKPathFillType.EvenOdd : SKPathFillType.Winding;
        canvas.Save();
        canvas.Translate(i % Columns * Cell + 12, i / Columns * Cell + 12);
        canvas.Scale(3);
        canvas.DrawPath(path, paint);
        canvas.Restore();
    }

    using SKData png = surface.Snapshot().Encode(SKEncodedImageFormat.Png, 100);
    File.WriteAllBytes(pngPath, png.ToArray());
    Console.WriteLine($"preview of {files.Length} icons -> {pngPath}");
}

// The app logo: a rounded tile with an indigo-to-sky gradient and the download-01 arrow in white.
// Renders every MSIX asset and AppIcon.ico, so the logo is changed here, not in an image editor.
void Logo()
{
    string assets = Path.Combine(root, "src", "Wintor.App", "Assets");
    // A slightly heavier stroke than the 1.5 of the UI icons reads better on the tile. The tray keeps 1.5:
    // one pixel at 16 px, as thin as the Windows icons next to it.
    using SKPath glyph = Glyph("download-01", 2);
    using SKPath trayGlyph = Glyph("download-circle-01", 1.5f);

    (string File, int Width, int Height, float TileShare)[] targets =
    [
        ("Square44x44Logo.scale-200.png", 88, 88, 1f),
        ("Square44x44Logo.targetsize-24_altform-unplated.png", 24, 24, 1f),
        ("Square44x44Logo.targetsize-48_altform-lightunplated.png", 48, 48, 1f),
        ("Square150x150Logo.scale-200.png", 300, 300, 0.6f),
        ("Wide310x150Logo.scale-200.png", 620, 300, 0.6f),
        ("SplashScreen.scale-200.png", 1240, 600, 0.4f),
        ("LockScreenLogo.scale-200.png", 48, 48, 1f),
        ("StoreLogo.png", 50, 50, 1f),
    ];
    foreach (var (file, width, height, share) in targets)
    {
        File.WriteAllBytes(Path.Combine(assets, file), Render(width, height, share));
        Console.WriteLine($"logo -> Assets/{file}");
    }

    WriteIco("AppIcon.ico", [16, 20, 24, 32, 40, 48, 64, 256], s => Render(s, s, 1f));

    // The monochrome tray icon: an arrow in a circle, line-drawn like the Windows icons next to it, in the taskbar's text color.
    // "Light" is for a light taskbar (a dark arrow), "Dark" for a dark one. Sizes cover the tray from 100 to 300%.
    int[] traySizes = [16, 20, 24, 32, 40, 48];
    WriteIco("TrayIconLight.ico", traySizes, s => RenderGlyph(s, new SKColor(0, 0, 0, 0xE4)));
    WriteIco("TrayIconDark.ico", traySizes, s => RenderGlyph(s, SKColors.White));

    // ICO with PNG entries (supported since Windows Vista).
    void WriteIco(string file, int[] sizes, Func<int, byte[]> render)
    {
        byte[][] images = sizes.Select(render).ToArray();
        using var ico = new BinaryWriter(File.Create(Path.Combine(assets, file)));
        ico.Write((short)0);
        ico.Write((short)1);
        ico.Write((short)sizes.Length);
        int offset = 6 + 16 * sizes.Length;
        for (int i = 0; i < sizes.Length; i++)
        {
            ico.Write((byte)(sizes[i] >= 256 ? 0 : sizes[i]));
            ico.Write((byte)(sizes[i] >= 256 ? 0 : sizes[i]));
            ico.Write((byte)0);
            ico.Write((byte)0);
            ico.Write((short)1);
            ico.Write((short)32);
            ico.Write(images[i].Length);
            ico.Write(offset);
            offset += images[i].Length;
        }

        foreach (byte[] image in images)
        {
            ico.Write(image);
        }

        Console.WriteLine($"logo -> Assets/{file}");
    }

    byte[] RenderGlyph(int size, SKColor color)
    {
        using var surface = SKSurface.Create(new SKImageInfo(size, size, SKColorType.Rgba8888, SKAlphaType.Premul));
        surface.Canvas.Clear(SKColors.Transparent);
        surface.Canvas.Scale(size / 24f);
        using var paint = new SKPaint { IsAntialias = true, Color = color };
        surface.Canvas.DrawPath(trayGlyph, paint);
        using SKData png = surface.Snapshot().Encode(SKEncodedImageFormat.Png, 100);
        return png.ToArray();
    }

    SKPath Glyph(string name, float strokeWidth)
    {
        XDocument svg = XDocument.Load(Path.Combine(iconsDir, name + ".svg"));
        foreach (XElement e in svg.Root!.Descendants())
        {
            e.SetAttributeValue("stroke-width", strokeWidth.ToString(CultureInfo.InvariantCulture));
        }

        string outline = Outline(svg);
        SKPath path = SKPath.ParseSvgPathData(outline[3..]);
        path.FillType = outline.StartsWith("F0") ? SKPathFillType.EvenOdd : SKPathFillType.Winding;
        return path;
    }

    byte[] Render(int width, int height, float share)
    {
        using var surface = SKSurface.Create(new SKImageInfo(width, height, SKColorType.Rgba8888, SKAlphaType.Premul));
        SKCanvas canvas = surface.Canvas;
        canvas.Clear(SKColors.Transparent);

        float tile = MathF.Min(width, height) * share;
        // Small sizes get a hair of margin so the tile does not touch the edge of the taskbar slot.
        float margin = tile <= 32 ? 1 : tile * 0.04f;
        var rect = SKRect.Create((width - tile) / 2 + margin, (height - tile) / 2 + margin, tile - 2 * margin, tile - 2 * margin);
        float radius = rect.Width * 0.24f;

        using var tilePaint = new SKPaint
        {
            IsAntialias = true,
            Shader = SKShader.CreateLinearGradient(
                new SKPoint(rect.Left, rect.Top),
                new SKPoint(rect.Right, rect.Bottom),
                [new SKColor(0x63, 0x66, 0xF1), new SKColor(0x0E, 0xA5, 0xE9)],
                SKShaderTileMode.Clamp),
        };
        canvas.DrawRoundRect(rect, radius, radius, tilePaint);

        float scale = rect.Width * 0.62f / 24f;
        canvas.Save();
        canvas.Translate(rect.MidX - 12 * scale, rect.MidY - 12 * scale);
        canvas.Scale(scale);
        using var glyphPaint = new SKPaint { IsAntialias = true, Color = SKColors.White };
        canvas.DrawPath(glyph, glyphPaint);
        canvas.Restore();

        using SKData png = surface.Snapshot().Encode(SKEncodedImageFormat.Png, 100);
        return png.ToArray();
    }
}

// The npm package stores each icon as [["path", { d: "...", strokeWidth: "1.5", ... }], ...].
static string JsToSvg(string js)
{
    var svg = new StringBuilder("<svg xmlns=\"http://www.w3.org/2000/svg\" width=\"24\" height=\"24\" viewBox=\"0 0 24 24\" fill=\"none\">\n");
    foreach (Match element in Regex.Matches(js, @"\[\s*""(\w+)""\s*,\s*\{(.*?)\}\s*\]", RegexOptions.Singleline))
    {
        svg.Append("  <").Append(element.Groups[1].Value);
        foreach (Match attr in Regex.Matches(element.Groups[2].Value, @"(\w+):\s*""([^""]*)"""))
        {
            if (attr.Groups[1].Value == "key")
            {
                continue;
            }

            string name = Regex.Replace(attr.Groups[1].Value, "([A-Z])", m => "-" + m.Value.ToLowerInvariant());
            svg.Append(' ').Append(name).Append("=\"").Append(attr.Groups[2].Value).Append('"');
        }

        svg.Append(" />\n");
    }

    return svg.Append("</svg>\n").ToString();
}

static string Outline(XDocument svg)
{
    XElement root = svg.Root!;
    string rootFill = (string?)root.Attribute("fill") ?? "black";
    var result = new SKPath();

    foreach (XElement element in root.Descendants())
    {
        using SKPath? shape = ToPath(element);
        if (shape is null)
        {
            continue;
        }

        string stroke = (string?)element.Attribute("stroke") ?? (string?)root.Attribute("stroke") ?? "none";
        string fill = (string?)element.Attribute("fill") ?? rootFill;

        if (fill != "none")
        {
            result = Union(result, shape);
        }

        if (stroke != "none")
        {
            using var paint = new SKPaint
            {
                Style = SKPaintStyle.Stroke,
                StrokeWidth = Number(element, "stroke-width", Number(root, "stroke-width", 1)),
                StrokeCap = Attr(element, "stroke-linecap") switch { "round" => SKStrokeCap.Round, "square" => SKStrokeCap.Square, _ => SKStrokeCap.Butt },
                StrokeJoin = Attr(element, "stroke-linejoin") switch { "round" => SKStrokeJoin.Round, "bevel" => SKStrokeJoin.Bevel, _ => SKStrokeJoin.Miter },
            };
            using var outline = new SKPath();
            paint.GetFillPath(shape, outline);
            result = Union(result, outline);
        }
    }

    // Path markup prefix: F0 = even-odd, F1 = nonzero. Keep whatever rule Skia's union produced,
    // otherwise the holes inside closed strokes get filled.
    string fillRule = result.FillType is SKPathFillType.EvenOdd or SKPathFillType.InverseEvenOdd ? "F0" : "F1";
    string data = Regex.Replace(result.ToSvgPathData(), @"-?\d+\.\d+(e-?\d+)?", m =>
        Math.Round(double.Parse(m.Value, CultureInfo.InvariantCulture), 3).ToString(CultureInfo.InvariantCulture));
    result.Dispose();
    return fillRule + " " + data;
}

static SKPath Union(SKPath a, SKPath b)
{
    SKPath? combined = a.Op(b, SKPathOp.Union);
    if (combined is null)
    {
        throw new InvalidOperationException("Path union failed.");
    }

    a.Dispose();
    return combined;
}

static SKPath? ToPath(XElement e)
{
    var path = new SKPath();
    switch (e.Name.LocalName)
    {
        case "path":
            path.Dispose();
            return SKPath.ParseSvgPathData((string)e.Attribute("d")!);
        case "circle":
            path.AddCircle(Number(e, "cx"), Number(e, "cy"), Number(e, "r"));
            return path;
        case "ellipse":
            float cx = Number(e, "cx"), cy = Number(e, "cy"), rx = Number(e, "rx"), ry = Number(e, "ry");
            path.AddOval(new SKRect(cx - rx, cy - ry, cx + rx, cy + ry));
            return path;
        case "rect":
            var rect = SKRect.Create(Number(e, "x"), Number(e, "y"), Number(e, "width"), Number(e, "height"));
            float r = Number(e, "rx", Number(e, "ry"));
            path.AddRoundRect(rect, r, Number(e, "ry", r));
            return path;
        case "line":
            path.MoveTo(Number(e, "x1"), Number(e, "y1"));
            path.LineTo(Number(e, "x2"), Number(e, "y2"));
            return path;
        case "polyline":
        case "polygon":
            float[] p = ((string)e.Attribute("points")!)
                .Split([' ', ','], StringSplitOptions.RemoveEmptyEntries)
                .Select(v => float.Parse(v, CultureInfo.InvariantCulture)).ToArray();
            path.MoveTo(p[0], p[1]);
            for (int i = 2; i + 1 < p.Length; i += 2)
            {
                path.LineTo(p[i], p[i + 1]);
            }

            if (e.Name.LocalName == "polygon")
            {
                path.Close();
            }

            return path;
        default:
            path.Dispose();
            return null;
    }
}

static string? Attr(XElement e, string name) => (string?)e.Attribute(name);

static float Number(XElement e, string name, float fallback = 0) =>
    e.Attribute(name) is { } a ? float.Parse(a.Value, CultureInfo.InvariantCulture) : fallback;

static string ToPascal(string kebab) =>
    string.Concat(kebab.Split('-', StringSplitOptions.RemoveEmptyEntries)
        .Select(p => char.ToUpperInvariant(p[0]) + p[1..]));

static string FindRepoRoot()
{
    for (var dir = new DirectoryInfo(AppContext.BaseDirectory); dir is not null; dir = dir.Parent)
    {
        if (File.Exists(Path.Combine(dir.FullName, "Wintor.sln")))
        {
            return dir.FullName;
        }
    }

    throw new InvalidOperationException("Run the tool from inside the Wintor repository.");
}
